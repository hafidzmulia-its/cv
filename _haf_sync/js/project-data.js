const createProjectScreenshots = (folder, title, scenes = []) => {
    if (!folder) {
        return [];
    }

    const fallbackScenes = [
        { title: 'Interface Overview', description: `High-level view of the primary solution for ${title}.` },
        { title: 'User Workflow', description: `The core action path providing value in ${title}.` },
        { title: 'Supporting Features', description: `Secondary capabilities enhancing the experience in ${title}.` }
    ];

    const activeScenes = scenes.length > 0 ? scenes : fallbackScenes;

    return activeScenes.map((scene, index) => ({
        image: `img/${folder}/${index + 1}.png`,
        title: `${title} - ${scene.title}`,
        description: scene.description
    }));
};

